#!/bin/sh
# Builds own test programs (tests/fixtures/ac6-src/<Name>/main.c) with Arm
# Compiler 6 into tests/fixtures/ac6/<Name>.axf.  Each is generated as a copy
# of the TestStdinoutUSART project with absolute library paths, built in target/.
# Usage: tools/build-own.sh [-b path/to/ITS-BRD-VSC] [Name...]   (default: all)
set -e
here=$(cd "$(dirname "$0")/.." && pwd)
brd="$here/../ITS-BRD-VSC"
if [ "$1" = "-b" ]; then brd=$2; shift 2; fi
brd=$(cd "$brd" && pwd)
. "$here/tools/arm-env.sh"
dest="$here/tests/fixtures/ac6"
mkdir -p "$dest"
template="$brd/Programs/TestStdinoutUSART"
if [ $# -eq 0 ]; then
    set -- $(cd "$here/tests/fixtures/ac6-src" && ls -d */ | tr -d /)
fi
for name in "$@"; do
    src="$here/tests/fixtures/ac6-src/$name"
    echo "== $name (own)"
    work="$here/target/ac6-build/$name"
    rm -rf "$work"
    mkdir -p "$work/Src" "$work/Inc"
    cp "$template/Inc/main.h" "$work/Inc/"
    cp "$src/main.c" "$work/Src/main.c"
    echo "# $name (generated by tools/build-own.sh)" > "$work/README.md"
    for f in csolution.yml cproject.yml; do
        sed -e "s|TestStdinoutUSART|$name|g" -e "s|\.\./\.\./|$brd/|g" \
            "$template/TestStdinoutUSART.$f" > "$work/$name.$f"
    done
    cp "$template/TestStdinoutUSART_ITSboard.sct" "$work/${name}_ITSboard.sct"
    cp "$template/vcpkg-configuration.json" "$work/"
    (cd "$work" && cbuild "$name.csolution.yml" --context .Debug --packs >build.log 2>&1) ||
        { grep -iE "error|warning:" "$work/build.log" | head -n 30 >&2; exit 1; }
    fromelf --elf --strip=debug,comment -o "$dest/$name.axf" "$(find "$work/out" -name "$name.axf" | head -n1)" >/dev/null
    # __FILE__ strings (asserts) contain the build directory: overwrite its
    # parent prefix with the same number of '/' so no offsets change.
    python3 - "$(dirname "$brd")" "$dest/$name.axf" <<'PY'
import sys
prefix = sys.argv[1].encode()
path = sys.argv[2]
data = open(path, "rb").read()
open(path, "wb").write(data.replace(prefix, b"/" * len(prefix)))
PY
done
