/// Memory-to-memory transfers and a PIO fed by the DMA: channel 0 copies
/// four words from flash to 0x2000_0100 and chains to channel 1, which
/// copies them to 0x2000_0200 as byte-swapped halfwords; the firmware
/// waits for channel 1's interrupt flag and writes 1 to 0x2000_0004. Then
/// channel 2, paced by PIO0's TX FIFO 0, feeds eight words of 0x5555_5555
/// to state machine 0, which shifts them out on GPIO 0 one bit every 10
/// cycles; after channel 2's flag the firmware writes 2 to 0x2000_0004:
///
/// ```text
/// vectors:
///     .word 0x20042000
///     .word 0x10000109
/// reset:
///     ldr  r0, =0x50000000    @ DMA channel 0
///     ldr  r1, =0x10000100 + (table - vectors)
///     str  r1, [r0, #0x00]    @ READ_ADDR
///     ldr  r1, =0x20000100
///     str  r1, [r0, #0x04]    @ WRITE_ADDR
///     movs r1, #4
///     str  r1, [r0, #0x08]    @ TRANS_COUNT
///     ldr  r2, =0x50000040    @ channel 1: the copy again, halfwords swapped
///     ldr  r1, =0x20000100
///     str  r1, [r2, #0x00]
///     ldr  r1, =0x20000200
///     str  r1, [r2, #0x04]
///     movs r1, #8
///     str  r1, [r2, #0x08]
///     ldr  r1, =0x005F8835    @ EN, halfword, INCR both, CHAIN_TO self, permanent, BSWAP
///     str  r1, [r2, #0x10]    @ AL1_CTRL (no trigger)
///     ldr  r1, =0x001F8839    @ EN, word, INCR both, CHAIN_TO 1, permanent
///     str  r1, [r0, #0x0C]    @ CTRL_TRIG
///     ldr  r3, =0x50000400    @ INTR
/// wait1:
///     ldr  r1, [r3]
///     lsrs r1, r1, #2         @ channel 1 done: bit 1 into carry
///     bcc  wait1
///     ldr  r4, =0x20000000
///     str  r1, [r4]           @ INTR >> 2 (channels 0 and 1 done: 0)
///     movs r1, #1
///     str  r1, [r4, #4]
///     @ PIO0 SM0: out pins, 1 on GPIO 0 every 10 cycles, autopull
///     ldr  r0, =0x40014004    @ GPIO0_CTRL
///     movs r1, #6             @ FUNCSEL = PIO0
///     str  r1, [r0]
///     ldr  r0, =0x50200000
///     ldr  r1, =0x6001        @ out pins, 1
///     str  r1, [r0, #0x48]
///     ldr  r5, =0x502000C8    @ SM0_CLKDIV
///     ldr  r1, =0x000A0000
///     str  r1, [r5, #0x00]    @ CLKDIV 10
///     movs r1, #0
///     str  r1, [r5, #0x04]    @ EXECCTRL: wrap 0..0
///     ldr  r1, =0x000A0000
///     str  r1, [r5, #0x08]    @ SHIFTCTRL: autopull, OUT to the right
///     ldr  r1, =0x04100000
///     str  r1, [r5, #0x14]    @ PINCTRL: OUT 1 pin at 0, SET 1 pin at 0
///     ldr  r1, =0xE081        @ set pindirs, 1
///     str  r1, [r5, #0x10]    @ SM0_INSTR
///     ldr  r2, =0x50000080    @ channel 2: 8 words to TXF0, paced by PIO0 TX0
///     ldr  r1, =0x10000100 + (pattern - vectors)
///     str  r1, [r2, #0x00]
///     ldr  r1, =0x50200010
///     str  r1, [r2, #0x04]
///     movs r1, #8
///     str  r1, [r2, #0x08]
///     ldr  r1, =0x00001019    @ EN, word, INCR_READ, CHAIN_TO self, DREQ PIO0_TX0
///     str  r1, [r2, #0x0C]
///     movs r1, #1
///     str  r1, [r0, #0x00]    @ SM0 on
/// wait2:
///     ldr  r1, [r3]
///     lsrs r1, r1, #3         @ channel 2 done: bit 2 into carry
///     bcc  wait2
///     movs r1, #2
///     str  r1, [r4, #4]
/// loop:
///     b    loop
///     .ltorg
///     .align 2
/// table:
///     .word 0x11223344, 0x55667788, 0x99AABBCC, 0xDDEEFF00
/// pattern:
///     .rept 8
///     .word 0x55555555
